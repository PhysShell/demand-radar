def _archive_preliminary_artifacts(run_dir: Path) -> None:
    """Copies the pre-finalize report/opportunities/verification so the
    before/after human review is auditable -- finalize is about to
    overwrite them. A no-op if already archived by an earlier finalize
    call (never clobbers an existing preliminary/ snapshot).
    """
    preliminary_dir = run_dir / "preliminary"
    if preliminary_dir.is_dir():
        return
    outputs_dir = run_dir / "outputs"
    targets = [
        (outputs_dir / "report.md", preliminary_dir / "outputs" / "report.md"),
        (outputs_dir / "opportunities.json", preliminary_dir / "outputs" / "opportunities.json"),
        (run_dir / "verification.json", preliminary_dir / "verification.json"),
    ]
    for src, dst in targets:
        if src.is_file():
            dst.parent.mkdir(parents=True, exist_ok=True)
            dst.write_bytes(src.read_bytes())


def _write_test_fixture_review_marker_if_applicable(
    run_dir: Path, *, store: Store, run_id: str
) -> None:
    """A separate, additive artifact -- deliberately never folded into
    AgentRunStatus or verification.schema.json's checks (Phase 2C-SMOKE's
    own scope boundary) -- so a synthetic pipeline-mechanics smoke run can
    never be mistaken for a completed, substantive review just because
    critic_status happened to read PASS. A no-op for a normal human-
    reviewed run, AND for a partial fixture batch: nothing is written
    unless every provenance record for this run came from a test fixture
    *and* every opportunity in the run has a verdict -- purity alone isn't
    enough, a partial fixture pass must not read as a completed one.
    """
    if _provenance_source_kinds(run_dir) != {"test_fixture"}:
        return
    opportunities = store.list_opportunity_cards_for_run(run_id)
    if not opportunities or not all(
        store.get_critic_verdict(card.id) is not None for card in opportunities
    ):
        return
    marker = {
        "review_channel_status": "TEST_FIXTURE_REVIEW",
        "pipeline_mechanics": "PASS",
        "substantive_review": "NOT_PERFORMED",
    }
    reviews_dir = run_dir / "reviews"
    reviews_dir.mkdir(parents=True, exist_ok=True)
    (reviews_dir / "review-channel-status.json").write_text(
        json.dumps(marker, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def finalize_run(
    *,
    store: Store,
    run_dir: Path,
    schemas_dir: Path,
    product: ProductConfig,
    run_id: str,
    now: datetime,
) -> DemandState:
    """Runs only deterministic_judge -> render_report -> verify_run against
    the store's current state (after any `review import` calls). Never
    calls an agent: both runner roles are NeverCalledRunner, so if either
    of those three functions ever referenced one, this would raise
    immediately rather than silently reclassifying or regenerating
    anything. Never reclassifies evidence or regenerates opportunities --
    classify/generate_opportunities/critic_review are simply never called.
    """
    state_path = run_dir / "state.json"
    if not state_path.is_file():
        raise FinalizeError(
            f"{state_path} does not exist -- run `demand-radar run` for run_id {run_id!r} first"
        )
    # dict[str, Any], not DemandState: TypedDict.update() rejects a plain
    # dict[str, Any] argument (mypy), so this stays untyped until the final
    # cast, matching graph/build.py::run_or_resume's own cast(DemandState, ...).
    state: dict[str, Any] = json.loads(state_path.read_text(encoding="utf-8"))

    _archive_preliminary_artifacts(run_dir)

    ctx = RunContext(
        store=store,
        analyst_runner=NeverCalledRunner(),
        critic_runner=NeverCalledRunner(),
        analyst_name="none",
        critic_name="none",
        product=product,
        run_dir=run_dir,
        schemas_dir=schemas_dir,
        now=now,
    )
    config: dict[str, Any] = {"configurable": {"ctx": ctx}}

    state.update(deterministic_judge(cast(DemandState, state), config))
    state.update(render_report(cast(DemandState, state), config))
    state.update(verify_run(cast(DemandState, state), config))

    state_path.write_text(json.dumps(state, indent=2, sort_keys=True), encoding="utf-8")
    _write_test_fixture_review_marker_if_applicable(run_dir, store=store, run_id=run_id)
    return cast(DemandState, state)
