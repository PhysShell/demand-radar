"""Phase 2C human review workflow: export a review packet, import completed
reviews, and finalize a run once they land. None of this calls a model —
`demand-radar run --critic human` is what defers the critic; everything
here operates on an already-completed (BLOCKED, preliminary) run.

Independent means independent of analyst execution: a review imported here
was not generated by the analyst provider, not a second same-provider
critique, and not produced by the worker agent that ran the trial. It is
not a claim that the reviewer is an independent market or research body —
a product-owner review is allowed (with `reviewer.conflict` disclosed) but
is never market validation.
"""

